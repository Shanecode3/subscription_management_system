import { ArrowRight, Play, ReceiptText, Search } from 'lucide-react';
import { useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { AppShell } from '../components/layout/AppShell';
import { Alert } from '../components/ui/Alert';
import { Badge } from '../components/ui/Badge';
import { Button } from '../components/ui/Button';
import { EmptyState } from '../components/ui/EmptyState';
import { PageHeader } from '../components/ui/PageHeader';
import { SelectField } from '../components/ui/SelectField';
import { cx } from '../lib/cx';
import { formatDate, formatMoney } from '../lib/format';
import { INVOICE_TONE } from '../lib/invoice-status';
import type { Invoice, InvoiceStatus } from '../lib/types';
import { useApiResource } from '../lib/use-api-resource';

const STATUS_OPTIONS: readonly InvoiceStatus[] = ['Draft', 'Confirmed', 'Paid', 'Cancelled'];

type LedgerView = 'all' | 'outstanding' | 'overdue';

const VIEW_OPTIONS: readonly { value: LedgerView; label: string }[] = [
  { value: 'all', label: 'All invoices' },
  { value: 'outstanding', label: 'Outstanding' },
  { value: 'overdue', label: 'Overdue' },
];

/**
 * The invoice ledger. The API already applies the tenant rule — a customer
 * session only ever receives its own invoices — so this page renders whatever
 * it is handed and never decides which rows are visible.
 */
export function InvoicesPage() {
  const { data, isLoading, error, reload } = useApiResource<Invoice[]>('/invoices');

  const [statusFilter, setStatusFilter] = useState('');
  const [view, setView] = useState<LedgerView>('all');
  const [query, setQuery] = useState('');

  const invoices = data ?? [];

  const totals = useMemo(() => {
    let outstanding = 0;
    let outstandingCount = 0;
    let collected = 0;
    let overdue = 0;

    for (const invoice of invoices) {
      if (invoice.status === 'Cancelled') continue;
      outstanding += invoice.balanceDue;
      if (invoice.balanceDue > 0) outstandingCount += 1;
      collected += invoice.amountPaid;
      if (invoice.isOverdue) overdue += 1;
    }

    return { outstanding, outstandingCount, collected, overdue };
  }, [invoices]);

  const visible = useMemo(() => {
    const needle = query.trim().toLowerCase();
    return invoices.filter((invoice) => {
      if (view === 'outstanding' && (invoice.status === 'Cancelled' || invoice.balanceDue <= 0)) {
        return false;
      }
      if (view === 'overdue' && !invoice.isOverdue) return false;
      if (statusFilter !== '' && invoice.status !== statusFilter) return false;
      if (needle === '') return true;
      return (
        invoice.invoiceNumber.toLowerCase().includes(needle) ||
        invoice.subscriptionNumber.toLowerCase().includes(needle) ||
        invoice.customerName.toLowerCase().includes(needle) ||
        invoice.customerEmail.toLowerCase().includes(needle)
      );
    });
  }, [invoices, statusFilter, query, view]);

  return (
    <AppShell>
      <div className="space-y-6">
        <PageHeader
          title="Invoices"
          description="Every invoice generated by a billing run, with the actions its current status allows."
          action={
            <Link to="/billing" className="btn-teal w-auto">
              <Play className="h-4 w-4" aria-hidden="true" />
              Billing day
            </Link>
          }
        />

        {isLoading ? (
          <div className="space-y-4">
            <div className="h-24 animate-pulse rounded-xl bg-slate-100" />
            <div className="h-72 animate-pulse rounded-xl bg-slate-100" />
          </div>
        ) : error ? (
          <div className="space-y-3">
            <Alert tone="error" title="Invoices could not be loaded">
              {error}
            </Alert>
            <Button variant="secondary" className="w-auto" onClick={reload}>
              Try again
            </Button>
          </div>
        ) : (
          <>
            <dl className="grid grid-cols-2 gap-3 sm:grid-cols-3">
              <div className="card px-4 py-3">
                <dt className="text-xs font-medium text-slate-500">Outstanding</dt>
                <dd className="mt-1 text-2xl font-semibold tabular-nums text-amber-700">
                  {formatMoney(totals.outstanding)}
                </dd>
              </div>
              <div className="card px-4 py-3">
                <dt className="text-xs font-medium text-slate-500">Collected</dt>
                <dd className="mt-1 text-2xl font-semibold tabular-nums text-emerald-700">
                  {formatMoney(totals.collected)}
                </dd>
              </div>
              <div className="card col-span-2 px-4 py-3 sm:col-span-1">
                <dt className="text-xs font-medium text-slate-500">Overdue</dt>
                <dd className="mt-1 text-2xl font-semibold tabular-nums text-rose-700">
                  {totals.overdue}
                </dd>
              </div>
            </dl>

            <div className="flex flex-wrap items-center gap-2" role="group" aria-label="Invoice view">
              {VIEW_OPTIONS.map((option) => {
                const count =
                  option.value === 'all'
                    ? invoices.length
                    : option.value === 'outstanding'
                      ? totals.outstandingCount
                      : totals.overdue;

                return (
                  <button
                    key={option.value}
                    type="button"
                    aria-pressed={view === option.value}
                    onClick={() => setView(option.value)}
                    className={cx(
                      'inline-flex items-center gap-2 rounded-full border px-3.5 py-1.5 text-sm font-medium transition-colors',
                      view === option.value
                        ? 'border-plum-600 bg-plum-50 text-plum-800'
                        : 'border-slate-200 bg-white text-slate-600 hover:bg-slate-50',
                    )}
                  >
                    {option.label}
                    <span
                      className={cx(
                        'rounded-full px-1.5 text-xs font-semibold tabular-nums',
                        view === option.value ? 'bg-plum-600 text-white' : 'bg-slate-100 text-slate-600',
                      )}
                    >
                      {count}
                    </span>
                  </button>
                );
              })}
            </div>

            <div className="card overflow-hidden">
              <div className="flex flex-wrap items-end gap-3 border-b border-slate-200 bg-slate-50/60 px-5 py-4">
                <div className="min-w-[180px] flex-1">
                  <SelectField
                    id="invoice-status-filter"
                    label="Status"
                    value={statusFilter}
                    onChange={(event) => setStatusFilter(event.target.value)}
                  >
                    <option value="">All statuses</option>
                    {STATUS_OPTIONS.map((status) => (
                      <option key={status} value={status}>
                        {status}
                      </option>
                    ))}
                  </SelectField>
                </div>

                <div className="min-w-[220px] flex-[2]">
                  <label htmlFor="invoice-search" className="field-label">
                    Find an invoice
                  </label>
                  <div className="relative">
                    <Search
                      className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-slate-400"
                      aria-hidden="true"
                    />
                    <input
                      id="invoice-search"
                      className="field-input pl-9"
                      value={query}
                      onChange={(event) => setQuery(event.target.value)}
                      placeholder="INV-2026-1001, contract or customer"
                    />
                  </div>
                </div>
              </div>

              {invoices.length === 0 ? (
                <div className="p-5">
                  <EmptyState
                    icon={ReceiptText}
                    title="No invoices yet"
                    description="Run billing day and one draft invoice appears here for every contract whose billing date has arrived."
                    action={
                      <Link to="/billing" className="btn-teal w-auto">
                        <Play className="h-4 w-4" aria-hidden="true" />
                        Go to billing day
                      </Link>
                    }
                  />
                </div>
              ) : visible.length === 0 ? (
                <p className="px-5 py-10 text-center text-sm text-slate-500">
                  No invoice matches those filters. Try a different status or search term.
                </p>
              ) : (
                <div className="overflow-x-auto">
                  <table className="w-full min-w-[960px] text-sm">
                    <thead>
                      <tr className="border-b border-slate-200 text-left text-xs font-semibold text-slate-500">
                        <th scope="col" className="px-5 py-2.5">Invoice</th>
                        <th scope="col" className="px-3 py-2.5">Customer</th>
                        <th scope="col" className="px-3 py-2.5">Contract</th>
                        <th scope="col" className="px-3 py-2.5">Issued</th>
                        <th scope="col" className="px-3 py-2.5">Due</th>
                        <th scope="col" className="px-3 py-2.5 text-right">Total</th>
                        <th scope="col" className="px-3 py-2.5 text-right">Balance</th>
                        <th scope="col" className="px-3 py-2.5">Status</th>
                        <th scope="col" className="px-5 py-2.5">
                          <span className="sr-only">Open</span>
                        </th>
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-slate-100">
                      {visible.map((invoice) => (
                        <tr key={invoice.id} className="hover:bg-slate-50/70">
                          <td className="px-5 py-3">
                            <Link
                              to={`/invoices/${invoice.id}`}
                              className="font-semibold text-plum-700 hover:text-plum-800 hover:underline"
                            >
                              {invoice.invoiceNumber}
                            </Link>
                            <p className="mt-0.5 text-xs text-slate-500">{invoice.planName}</p>
                          </td>
                          <td className="px-3 py-3">
                            <p className="font-medium text-ink">{invoice.customerName}</p>
                            <p className="text-xs text-slate-500">{invoice.customerEmail}</p>
                          </td>
                          <td className="px-3 py-3 text-slate-600">{invoice.subscriptionNumber}</td>
                          <td className="px-3 py-3 tabular-nums text-slate-600">
                            {formatDate(invoice.issueDate)}
                          </td>
                          <td className="px-3 py-3 tabular-nums text-slate-600">
                            {formatDate(invoice.dueDate)}
                            {invoice.isOverdue ? (
                              <span className="ml-1 block text-xs font-semibold text-rose-600">
                                {invoice.daysOverdue} day{invoice.daysOverdue === 1 ? '' : 's'}{' '}
                                late
                              </span>
                            ) : null}
                          </td>
                          <td className="px-3 py-3 text-right font-semibold tabular-nums text-ink">
                            {formatMoney(invoice.totalAmount)}
                          </td>
                          <td
                            className={
                              invoice.balanceDue > 0
                                ? 'px-3 py-3 text-right tabular-nums text-amber-700'
                                : 'px-3 py-3 text-right tabular-nums text-slate-400'
                            }
                          >
                            {formatMoney(invoice.balanceDue)}
                          </td>
                          <td className="px-3 py-3">
                            <Badge tone={INVOICE_TONE[invoice.status]}>{invoice.status}</Badge>
                          </td>
                          <td className="px-5 py-3 text-right">
                            <Link
                              to={`/invoices/${invoice.id}`}
                              aria-label={`Open ${invoice.invoiceNumber}`}
                              className="inline-flex rounded-lg p-1.5 text-slate-400 hover:bg-slate-100 hover:text-ink"
                            >
                              <ArrowRight className="h-4 w-4" aria-hidden="true" />
                            </Link>
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              )}
            </div>
          </>
        )}
      </div>
    </AppShell>
  );
}
